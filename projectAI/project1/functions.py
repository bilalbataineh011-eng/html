

# تعريف الدالة
def add_numbers(a, b):
    # هذه الدالة تستقبل رقمين
    # وتعيد مجموعهم
    result = a + b
    return result


# =====================================
# استخدام الدالة
# =====================================

# استدعاء الدالة وتمرير قيم لها
sum1 = add_numbers(5, 3)
sum2 = add_numbers(10, 20)

print("ناتج 5 + 3 =", sum1)
print("ناتج 10 + 20 =", sum2)
